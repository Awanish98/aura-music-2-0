package echo.music.iad1tya.cinematic

/** Backdrop recipe. Each entry is drawn by a distinct branch of the renderer. */
enum class CinematicBackdrop {
  AMBIENT,
  GRADIENT,
  EDITORIAL,
  NEON,
  CRIMSON,
  DREAM,
  FILM,
  GLITCH,
  MOTION,
  CHROME,
  BLOOM,
  RAIN,
  DEPTH,
  SUNSET,
  CHAOS,
}

/** Typography family used by a theme. */
enum class CinematicTypeface {
  SERIF_ITALIC,
  SERIF,
  SANS,
  SANS_CONDENSED,
  MONO,
  DISPLAY,
}

/** Word movement recipe. */
enum class CinematicMotion {
  FLOAT,
  DRIFT,
  SLIDE,
  PULSE,
  GLITCH,
  BLUR,
  CHROME,
  PETAL,
  RAIN,
  PERSPECTIVE,
  SCATTER,
  CHAOS,
}

enum class TempoBias { SLOW, MEDIUM, FAST, ANY }

